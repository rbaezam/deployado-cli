package cmd

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// nginxHardeningCheck inspects a service's build context for the
// "Dockerfile with nginx + nginx config without hardening rules"
// pattern that bit booky-web — the SPA fallback returned 200 to
// /.env, /.git/config, /wp-admin/, etc., because no `location`
// blocks short-circuited it.
//
// Returns a list of warning messages (empty if no issues found).
// Pure function on the filesystem — no network, safe to call in
// dry-run mode.

// nginxHardeningWarnings scans svcAbsPath (the resolved absolute
// path of a service's build context) for nginx configs that ship
// without scanner-path protection. Catches the common case of a
// SPA Dockerfile that copies `nginx.conf` or `default.conf`
// alongside the build artifacts.
//
// Returns nil if:
//   - No Dockerfile is present (autogenerated path — agent's
//     static_dockerfile.go already includes hardening).
//   - The Dockerfile doesn't reference nginx.
//   - The nginx config file we find already has hardening rules.
//
// Only checks `nginx.conf` and `default.conf` at the build-context
// root — covers the >90% case without recursing through the tree.
func nginxHardeningWarnings(svcAbsPath string) []string {
	dockerfilePath := filepath.Join(svcAbsPath, "Dockerfile")
	dockerfile, err := os.ReadFile(dockerfilePath)
	if err != nil {
		return nil
	}

	if !dockerfileUsesNginx(dockerfile) {
		return nil
	}

	// Look for the nginx config alongside the Dockerfile. The two
	// canonical names cover almost every SPA template we've seen.
	candidates := []string{"nginx.conf", "default.conf"}

	var warnings []string
	foundAny := false

	for _, name := range candidates {
		path := filepath.Join(svcAbsPath, name)
		body, err := os.ReadFile(path)
		if err != nil {
			continue
		}
		foundAny = true

		if !nginxConfigHasHardening(body) {
			warnings = append(warnings,
				fmt.Sprintf(
					"%s ships with an nginx Dockerfile but no scanner-path "+
						"protection. Requests to /.env, /.git/config, "+
						"/wp-admin/, /xmlrpc.php and similar will fall through "+
						"to the SPA fallback and return 200 — polluting access "+
						"logs and giving scanners false positives. "+
						"Add `location ~ /\\.` deny rules before `location /`. "+
						"See: https://docs.deployado.com/nginx-hardening",
					name,
				),
			)
		}
	}

	// Dockerfile says nginx, COPYs *.conf, but neither expected file
	// is at the root — heads-up but not a hard error (the config could
	// live in a subdirectory or be generated at build time).
	if !foundAny && dockerfileCopiesNginxConf(dockerfile) {
		warnings = append(warnings,
			"Dockerfile references an nginx config that we couldn't locate "+
				"at the build-context root. If your config doesn't deny "+
				"scanner paths (/.env, /.git/, /wp-admin/, etc.), they'll "+
				"reach the SPA fallback. "+
				"See: https://docs.deployado.com/nginx-hardening")
	}

	return warnings
}

// dockerfileUsesNginx returns true if the Dockerfile pulls a nginx
// image at any stage. Case-insensitive — `FROM Nginx:alpine` is
// just as legitimate as `FROM nginx:alpine`.
func dockerfileUsesNginx(dockerfile []byte) bool {
	lower := strings.ToLower(string(dockerfile))
	// Match `from nginx` or `from <anything>/nginx` (e.g.
	// `from gcr.io/distroless/nginx`). Avoid false positives on
	// strings that just mention nginx in a comment.
	for _, line := range strings.Split(lower, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "from ") {
			if strings.Contains(trimmed, "nginx") {
				return true
			}
		}
	}
	return false
}

// dockerfileCopiesNginxConf returns true if the Dockerfile has a
// COPY line that mentions a .conf file destined for nginx's
// configuration directory. Used to flag the "config is somewhere
// we can't see" case.
func dockerfileCopiesNginxConf(dockerfile []byte) bool {
	lower := strings.ToLower(string(dockerfile))
	for _, line := range strings.Split(lower, "\n") {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "copy ") {
			continue
		}
		if strings.Contains(trimmed, "/etc/nginx") || strings.Contains(trimmed, "nginx.conf") {
			return true
		}
	}
	return false
}

// nginxConfigHasHardening returns true if the config appears to
// have at least one of the canonical hardening rules. We're
// permissive — any single rule signals the user has thought about
// it. We don't grade the quality.
//
// The patterns mirror what we now ship in the agent's autogenerated
// template (static_dockerfile.go) and what we recommend in the docs.
func nginxConfigHasHardening(body []byte) bool {
	lower := strings.ToLower(string(body))

	patterns := []string{
		// Dotfile deny — most common form.
		`location ~ /\.`,
		`location ~* /\.`,
		// Specific scanner paths.
		"wp-admin",
		"xmlrpc",
		// Explicit deny-all.
		"deny all",
	}

	for _, p := range patterns {
		if strings.Contains(lower, p) {
			return true
		}
	}
	return false
}
